 *    @file     CurveHermite.cs
 *    @brief    エルミート曲線
 *
 *    ２点の座標と各点におけるベクトルから描く曲線です。
 *
 */
//*****************************************************************************************************************
//*****************************************************************************************************************
//*****************************************************************************************************************
using UnityEngine;

namespace SGSys
{
	public static partial class Math
	{
		public class CurveHermite : ICurveEvaluator
		{
			public	Vector3		p0		{ get; set; }
			public	Vector3		v0		{ get; set; }
			public	Vector3		p1		{ get; set; }
			public	Vector3		v1		{ get; set; }

			//==========================================================================
			/**
			 *    @brief       コンストラクタ
			 */
			//==========================================================================
			public CurveHermite() : this( Vector3.zero, Vector3.zero, Vector3.zero, Vector3.zero )
			{
			}

			//==========================================================================
			/**
			 *    @brief       コンストラクタ
			 *
			 *    @param[in]   p0_      始点
			 *    @param[in]   v0_      p0上でのベクトル
			 *    @param[in]   p1_      終点
			 *    @param[in]   v1_      p1上でのベクトル
			 */
			//==========================================================================
			public CurveHermite( Vector3 p0_, Vector3 v0_, Vector3 p1_, Vector3 v1_ )
			{
				this.p0 = p0_;
				this.v0 = v0_;
				this.p1 = p1_;
				this.v1 = v1_;
			}

			//==========================================================================
			/**
			 *    @brief       座標計算
			 *
			 *    @param[in]   t     媒介変数(0.0～1.0)
			 *    @return      曲線上の座標
			 */
			//==========================================================================
			public Vector3 Evaluate( float t )
			{
				float t2 = t * t;
				float t3 = t2 * t;
				
				//f(t) = (2p0 + v0 - 2p1 + v1) * t3
				//     + (-3p0 - 2v0 + 3p1 - v1) * t2
				//     + (v0) * t
				//     + p0
				
				Vector3	v = ( (2.0f*this.p0)  + this.v0 - (2.0f*this.p1) + this.v1 ) * t3
				          + ( (-3.0f*this.p0) - (2.0f*this.v0) + (3.0f*this.p1) - this.v1 ) * t2
				          + this.v0 * t
				          + this.p0;
				return v;
			}
		}
	}
}
